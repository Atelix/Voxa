import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const marker = "<!-- Generated by tools/ai/sync-skills.mjs; edit the source and regenerate. -->";
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && !["--check", "--write"].includes(args[0]))) {
    console.error("Usage: node tools/ai/sync-skills.mjs [--check|--write]");
    process.exit(1);
}
const write = args[0] === "--write";

async function main() {
    const manifest = JSON.parse(await readFile(resolve(root, "docs/ai/ecc/manifest.json"), "utf8"));
    if (manifest.repository !== "https://github.com/affaan-m/ECC" || !/^[a-f0-9]{40}$/.test(manifest.revision)) {
        throw new Error("The ECC manifest must pin the official repository and a full commit SHA.");
    }

    const referencePaths = new Set();
    for (const file of manifest.files) {
        if (!file.path.startsWith("docs/ai/ecc/") || file.path.includes("..") || !/^[a-f0-9]{64}$/.test(file.sha256)) {
            throw new Error("Invalid ECC reference path or SHA-256 hash.");
        }
        const contents = await readFile(resolve(root, file.path));
        const hash = createHash("sha256").update(contents).digest("hex");
        if (hash !== file.sha256) {
            throw new Error("ECC reference differs from its pinned source: " + file.path);
        }
        referencePaths.add(file.path);
    }
    if (!referencePaths.has("docs/ai/ecc/LICENSE")) {
        throw new Error("The ECC MIT license must be included and verified.");
    }

    for (const integration of manifest.integrations) {
        if (!referencePaths.has(integration.reference) || !integration.canonical.startsWith(".claude/skills/") || integration.canonical.includes("..")) {
            throw new Error("Invalid integrated ECC skill: " + integration.name);
        }
        const canonical = await readFile(resolve(root, integration.canonical), "utf8");
        if (!canonical.includes(integration.reference)) {
            throw new Error("Canonical skill must include its ECC reference: " + integration.name);
        }
    }

    const expected = new Map();
    for (const skill of manifest.skills) {
        if (!/^[a-z0-9-]+$/.test(skill.name) || skill.name.length > 60) {
            throw new Error("Invalid ECC skill name: " + skill.name);
        }
        const reference = "docs/ai/ecc/skills/" + skill.name + "/SKILL.md";
        if (!referencePaths.has(reference)) {
            throw new Error("ECC skill has no verified reference: " + skill.name);
        }
        const contents = [
            "---",
            "name: ecc-" + skill.name,
            "description: " + JSON.stringify(skill.description),
            "---",
            "",
            marker,
            "",
            "# ECC: " + skill.title,
            "",
            "Follow [AGENTS.md](../../../AGENTS.md), .editorconfig and the requested scope.",
            "Apply the project adaptations below before the generic upstream examples.",
            "",
            "## Project adaptations",
            "",
            ...skill.adaptations.map((adaptation) => "- " + adaptation),
            "",
            "## Upstream reference",
            "",
            "Read [ECC " + skill.title + "](../../../" + reference + ") and apply the relevant sections.",
            "Use only available tools and task-relevant references. Upstream package commands,",
            "framework examples, agent names and scripts are illustrative; use the project's configured",
            "commands and existing skills. Perform research and review inline when delegation is",
            "unavailable or outside the authorized task.",
            "",
        ].join("\n");
        const path = ".agents/skills/ecc-" + skill.name + "/SKILL.md";
        if (expected.has(path)) {
            throw new Error("Duplicate ECC skill: " + skill.name);
        }
        expected.set(path, contents);
        const claudeAdapter = [
            contents.slice(0, contents.indexOf("\n\n")),
            "",
            marker,
            "",
            "# ECC: " + skill.title,
            "",
            "Read and follow the [canonical shared skill](../../../" + path + ") before continuing.",
            "Resolve its references relative to that canonical directory. AGENTS.md governs",
            "architecture, formatting and required validation. This entry is a discovery bridge.",
            "",
        ].join("\n");
        expected.set(".claude/skills/ecc-" + skill.name + "/SKILL.md", claudeAdapter);
    }

    const claudeSkills = await readdir(resolve(root, ".claude/skills"), { withFileTypes: true });
    for (const directory of claudeSkills) {
        if (!directory.isDirectory() || directory.name.startsWith("ecc-")) {
            continue;
        }
        const source = ".claude/skills/" + directory.name + "/SKILL.md";
        const original = await readFile(resolve(root, source), "utf8");
        const frontmatter = original.match(/^---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/);
        if (!frontmatter || !/^name:\s*\S+/m.test(frontmatter[0]) || !/^description:/m.test(frontmatter[0])) {
            throw new Error("Missing skill metadata: " + source);
        }
        // Retain folded/multiline descriptions, but omit Claude-only discovery fields.
        const metadata = [];
        let include = false;
        for (const line of frontmatter[0].trimEnd().split(/\r?\n/).slice(1, -1)) {
            if (/^[^\s#]/.test(line)) include = /^(name|description):/.test(line);
            if (include) metadata.push(line);
        }
        const contents = [
            "---\n" + metadata.join("\n").trimEnd() + "\n---",
            "",
            marker,
            "",
            "# Project: " + directory.name,
            "",
            "Read and follow the [canonical project skill](../../../" + source + ") before continuing.",
            "Resolve its references, scripts, assets and licenses relative to that canonical directory.",
            "The repository's AGENTS.md governs architecture, formatting and required validation.",
            "",
        ].join("\n");
        expected.set(".agents/skills/" + directory.name + "/SKILL.md", contents);
    }

    const claude = await readFile(resolve(root, "CLAUDE.md"), "utf8");
    if (!/^@AGENTS\.md\s*$/m.test(claude)) {
        throw new Error("CLAUDE.md must import the shared AGENTS.md.");
    }

    const problems = [];
    for (const [path, contents] of expected) {
        if (write) {
            await mkdir(dirname(resolve(root, path)), { recursive: true });
            await writeFile(resolve(root, path), contents);
        } else {
            const actual = await readFile(resolve(root, path), "utf8").catch((error) => {
                if (error.code !== "ENOENT") throw error;
                return null;
            });
            if (actual !== contents) problems.push(path);
        }
    }
    const catalogs = new Map();
    for (const harness of [".agents", ".claude"]) {
        const names = new Map();
        const descriptions = new Map();
        const directories = await readdir(resolve(root, harness + "/skills"), { withFileTypes: true });
        for (const directory of directories) {
            if (!directory.isDirectory()) continue;
            const path = harness + "/skills/" + directory.name + "/SKILL.md";
            const contents = await readFile(resolve(root, path), "utf8").catch((error) => {
                if (error.code !== "ENOENT") throw error;
                return "";
            });
            if (!expected.has(path) && (directory.name.startsWith("ecc-") || contents.includes(marker))) {
                problems.push(path + " (stale generated adapter; remove explicitly)");
            }
            if (!contents) continue;
            if (manifest.retiredSkills.includes(directory.name)) {
                problems.push(path + " (retired overlapping skill)");
            }
            const metadata = contents.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/)?.[1];
            const name = metadata?.match(/^name:\s*(?:"([^"]+)"|'([^']+)'|([^\s]+))\s*$/m);
            const identity = name?.[1] ?? name?.[2] ?? name?.[3];
            const description = metadata?.match(/^description:[^\n]*(?:\n[ \t]+[^\n]*)*/m)?.[0];
            if (!identity || !description) {
                problems.push(path + " (missing skill identity or description)");
                continue;
            }
            const normalized = description.replace(/^description:\s*/, "").replace(/^[>|][-+]?\s*/, "")
                .replace(/^['"]|['"]$/g, "").replace(/\s+/g, " ").trim().toLowerCase();
            if (names.has(identity)) {
                problems.push(path + " (duplicate skill name: " + identity + "; also " + names.get(identity) + ")");
            }
            if (descriptions.has(normalized)) {
                problems.push(path + " (duplicate skill description; also " + descriptions.get(normalized) + ")");
            }
            names.set(identity, path);
            descriptions.set(normalized, path);
        }
        catalogs.set(harness, new Set(names.keys()));
    }
    const codexNames = catalogs.get(".agents");
    const claudeNames = catalogs.get(".claude");
    if (codexNames.size !== claudeNames.size || [...codexNames].some((name) => !claudeNames.has(name))) {
        problems.push("Codex and Claude must expose the same distinct skill catalog.");
    }
    if (problems.length > 0) {
        throw new Error("Skill adapters are out of sync; run with --write and review:\n" + problems.join("\n"));
    }
    console.log(
        (write ? "Generated" : "Verified") + " " + expected.size + " skill adapters; " +
        manifest.files.length + " pinned ECC references, the Claude import and " +
        codexNames.size + " distinct skills per tool verified.",
    );
}

main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
});
